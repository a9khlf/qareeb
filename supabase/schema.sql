-- 1) TABLES -------------------------------------------------

create table public.centers (
  id        text primary key,                       -- e.g. 'excel'
  grp       text not null check (grp in ('center','area')),
  name_en   text not null,
  name_ar   text not null,
  lat       double precision not null,
  lng       double precision not null,
  sort      int not null default 0
);

create table public.listings (
  id          bigint generated by default as identity primary key,
  type        text not null check (type in ('room','studio','apartment')),
  area        text not null,
  price       int  not null check (price > 0),       -- RM per month
  status      text not null default 'available' check (status in ('available','reserved','taken')),
  lat         double precision not null,
  lng         double precision not null,
  beds        int  not null default 1,
  furnished   boolean not null default true,
  bills       boolean not null default false,        -- bills included?
  min_stay    int  not null default 12,              -- minimum stay in months
  gender      text not null default 'mixed' check (gender in ('mixed','women','men','family')),
  title_en    text not null,
  title_ar    text not null,
  desc_en     text not null default '',
  desc_ar     text not null default '',
  photos      text[] not null default '{}',          -- image URLs
  video       text   not null default '',            -- video URL (optional)
  colors      text[] not null default '{"#1f6f78","#5aa9a8"}',  -- placeholder gradient
  -- trust & fit (only set true when you REALLY did the check)
  v_video     boolean not null default false,        -- live video tour done
  v_owner     boolean not null default false,        -- owner identity checked
  v_visited   boolean not null default false,        -- visited in person
  mosque_min  int,                                   -- walking minutes to mosque
  halal_min   int,                                   -- walking minutes to halal food
  arabic      boolean not null default false,        -- Arabic-speaking owner/tenants
  published   boolean not null default true,         -- untick to hide a room
  created_at  timestamptz not null default now()
);

create table public.requests (
  id          bigint generated by default as identity primary key,
  listing_id  bigint references public.listings(id) on delete set null,
  name        text not null,
  whatsapp    text not null,
  center      text,
  note        text,
  created_at  timestamptz not null default now()
);

-- 2) SECURITY (Row Level Security) ---------------------------
-- The "anon" key is public (it sits inside the website), so these
-- rules are what protect your data.

alter table public.centers  enable row level security;
alter table public.listings enable row level security;
alter table public.requests enable row level security;

-- Anyone may READ centers and published listings.
create policy "public read centers"
  on public.centers for select to anon, authenticated using (true);

create policy "public read published listings"
  on public.listings for select to anon, authenticated using (published = true);

-- Anyone may SEND a request, but nobody can read, change or delete requests
-- through the website. You read them in the Supabase dashboard (Table Editor).
create policy "public can send a request"
  on public.requests for insert to anon, authenticated
  with check (
    length(trim(name)) between 1 and 100
    and length(trim(whatsapp)) between 6 and 25
    and (note is null or length(note) <= 500)
  );

-- No insert/update/delete policies exist for centers or listings, so only you
-- (logged in to the dashboard) can add or edit rooms.

