-- Missing-center suggestions: anyone may add one (the checks below keep the data sane);
-- only admins can read or delete them (policies are in admin.sql).
create table if not exists public.center_requests (
  id         bigint generated by default as identity primary key,
  name       text not null check (length(trim(name)) between 1 and 120),
  lat        double precision not null check (lat between 0 and 8),
  lng        double precision not null check (lng between 99 and 120),
  source     text not null default 'search' check (source in ('search','pin')),
  created_at timestamptz not null default now()
);
alter table public.center_requests enable row level security;

drop policy if exists "public can suggest a center" on public.center_requests;
create policy "public can suggest a center" on public.center_requests
  for insert to anon, authenticated with check (true);

grant insert on public.center_requests to anon, authenticated;
grant usage, select on sequence public.center_requests_id_seq to anon, authenticated;
